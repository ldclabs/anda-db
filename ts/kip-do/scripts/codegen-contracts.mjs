#!/usr/bin/env node
/** Generate static draft-2020 validators: Workers must never compile with eval. */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'
import Ajv from 'ajv/dist/2020.js'
import addFormats from 'ajv-formats'
import standalone from 'ajv/dist/standalone/index.js'
import { _ } from 'ajv/dist/compile/codegen/index.js'
import { isTimestamp } from '../src/timestamp-format.ts'
import { canonicalize, parseCanonicalJson } from '@ldclabs/kip-lang'
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../..')
const dir = resolve(root, 'rs/anda_kip/schemas')
const documents = Object.fromEntries(readdirSync(dir).filter((s) => s.endsWith('.json')).sort().map((name) => {
  const value = parseCanonicalJson(readFileSync(resolve(dir, name), 'utf8'))
  return [value.$id, value]
}))
const ajv = new Ajv({ strict: false, allErrors: true, verbose: true, inlineRefs: false, code: { source: true, esm: true, formats: _`timestampFormats` } })
addFormats(ajv)
ajv.addFormat('date-time', { type: 'string', validate: isTimestamp })
ajv.addFormat('timestamp', { type: 'string', validate: isTimestamp })
for (const schema of Object.values(documents)) ajv.addSchema(schema)
const contracts = new Map()
function collect(value) {
  if (Array.isArray(value)) return value.forEach(collect)
  if (!value || typeof value !== 'object') return
  for (const [key, child] of Object.entries(value)) {
    if (key === 'value_schema') contracts.set(canonicalize(child), child)
    else collect(child)
  }
}
collect(parseCanonicalJson(readFileSync(resolve(root, 'rs/anda_cognitive_nexus/profiles/cognitive-memory-2.1.0.json'), 'utf8')))
// Public companion schemas and named record definitions can be checked by SDKs.
for (const [id, schema] of Object.entries(documents)) {
  contracts.set(canonicalize({ $ref: id }), { $ref: id })
  for (const name of Object.keys(schema.$defs ?? {})) {
    const ref = { $ref: `${id}#/$defs/${name}` }
    contracts.set(canonicalize(ref), ref)
  }
}
const names = {}; const bindings = []
let i = 0
for (const [key, schema] of [...contracts].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)) {
  const id = `urn:anda:validator:${i}`
  ajv.addSchema(schema, id)
  names[`contract${i}`] = id
  bindings.push(`${JSON.stringify(key)}: contract${i}`)
  i++
}
let code = standalone(ajv, names)
// Ajv's standalone emitter uses require for helpers even in ESM mode. Static
// imports keep the generated module portable to Workers without runtime eval.
const imports = new Map()
code = code.replace(/require\("([^"]+)"\)/g, (_, path) => {
  if (!imports.has(path)) imports.set(path, `runtime${imports.size}`)
  return imports.get(path)
})
const header = [...imports].map(([path, name]) => `import * as ${name}_module from ${JSON.stringify(path+'.js')};\nconst ${name} = ${name}_module.default && typeof ${name}_module.default === "object" ? ${name}_module.default : ${name}_module;`).join('\n')
const memoryBundles = parseCanonicalJson(readFileSync(resolve(root, 'rs/anda_kip/profiles/memory-bundles.json'), 'utf8'))
const digests = Object.fromEntries(Object.entries(documents).map(([id, schema]) => [id, 'sha256:'+createHash('sha256').update(canonicalize(schema)).digest('hex')]))
const formatsHeader = `import { fullFormats } from 'ajv-formats/dist/formats.js'\nimport { isTimestamp } from '../timestamp-format.js'\nconst timestampFormats = { ...fullFormats, 'date-time': { validate: isTimestamp }, timestamp: { validate: isTimestamp } };`
const out = `// @ts-nocheck\n// Generated by scripts/codegen-contracts.mjs. No runtime code generation.\nimport type { JsonMap } from '../json.js'\n${header}\n${formatsHeader}\n${code}\nexport const VALUE_VALIDATORS = {${bindings.join(',\n')}};\nexport const SCHEMA_DOCUMENTS: Record<string, JsonMap> = ${JSON.stringify(documents,null,2)};\nexport const SCHEMA_DIGESTS: Record<string, string> = ${JSON.stringify(digests,null,2)};\nexport const MEMORY_BUNDLE_MANIFEST: JsonMap = ${JSON.stringify(memoryBundles,null,2)};\n`
writeFileSync(resolve(root,'ts/kip-do/src/schema/contracts.generated.ts'),out)
console.log(`Generated ${contracts.size} static validators (${out.length} bytes)`)
